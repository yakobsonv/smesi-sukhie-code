/** Настройки анимации «сыплется сухая смесь» на первом экране главной (src/lib/pour-hero.ts).
 *  Все размеры — в CSS-пикселях, время — в секундах. Два набора: `desktop` — экран от 1100 px,
 *  где справа стоят упаковки (струя идёт в щели между ними, куча — под ними); `mobile` — всё уже,
 *  где упаковок нет (струя идёт по левому полю, куча — узкой полосой под кнопками). */

export interface PourMode {
  /** потолок одновременно летящих и скатывающихся зёрен (по заданию ≤ 1500 / ≤ 600) */
  maxGrains: number;
  /** сколько зёрен в секунду выходит из «жерла» */
  rate: number;
  /** потолок облачков пыли */
  maxDust: number;
  /** высота вершины кучи — доля высоты первого экрана (по заданию ≤ 0,18) */
  peak: number;
  /** крутизна склона: px высоты на px ширины (≈ угол естественного откоса; 0,5 ≈ 27°) */
  slope: number;
  /** потолок высоты вершины, px (если задан) */
  peakMaxPx?: number;
  /** ширина колонки карты высот, px */
  col: number;
  /** насколько струю может увести вбок, px (дальше не пускаем: рядом текст или упаковки) */
  drift: number;
}

