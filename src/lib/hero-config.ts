import { POUR } from './pour-config';

export interface ParticleMode {
  /** сколько частиц в облаке (один Points, один вызов отрисовки) */
  count: number;
  /** шаг сетки, которой «прощупываются» буквы заголовка, px: меньше — плотнее буквы */
  sampleStep: number;
}

export interface ShowcaseMode {
  /** высота активного мешка — доля видимой высоты сцены */
  activeHeight: number;
  /** шаг между мешками по горизонтали — доля видимой ширины сцены (на телефоне соседи видны частично) */
  spacing: number;
  /** насколько дальше уходит каждый следующий сосед, единиц сцены (высота мешка ≈ 1,6) */
  depth: number;
  /** поворот соседей к центру, рад */
  turn: number;
  /** сколько соседей с каждой стороны видно (дальше — растворяются) */
  visible: number;
  /** подъём мешка над центром сцены — доля высоты мешка (на телефоне ниже: над ним кнопка «Пропустить») */
  lift: number;
}

